def main() -> int:
    bad = 0
    for path, old, new in EDITS:
        src = io.open(path, encoding="utf-8").read()
        n = src.count(old)
        if n != 1:
            print(f"[MISS] {path.name}: 命中 {n} 次（应为 1）\n    {old[:70]!r}")
            bad += 1
            continue
        io.open(path, "w", encoding="utf-8", newline="").write(src.replace(old, new))
        print(f"[ok] {path.name}: {old.strip().splitlines()[0][:52]}…")
    if bad:
        print(f"\n有 {bad} 处没改上 —— 别当成功。")
        return 1
    print("\n全部改上。")
    return 0


if __name__ == "__main__":
    sys.exit(main())
